"""Recorded component terms and edition availability: writes docs/licences.md from
orchestrator/licences.py and the options (`make licences`). A test checks the file is up to date.

    uv run python bench/licences_report.py          # rewrite docs/licences.md
    uv run python bench/licences_report.py --check  # exit 1 if it is out of date
"""
from __future__ import annotations

import argparse
import dataclasses
import importlib.util
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from gpu_worker.worker import CELL_FINDERS, EMBED_MODELS, OP_COMPONENTS, SEGMENT_MODELS  # noqa: E402
from orchestrator import licences  # noqa: E402
from orchestrator.options import GROUPS, Settings  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "licences.md"
PYPROJECT = ROOT / "services" / "pyproject.toml"
TIER_WORDS = {"open": "open", "terms": "terms", "noncommercial": "**non-commercial**"}


def _groups_by_package() -> dict[str, str]:
    """Python package -> the dependency group that installs it (pyproject.toml)."""
    found = {}
    for group, body in re.findall(r'^(\w+) = \[(.*?)\]', PYPROJECT.read_text(), re.M | re.S):
        for package in re.findall(r'"([A-Za-z0-9_.-]+)', body):
            found[package.lower()] = group
    return found


def _defaults(edition: str) -> dict[str, str]:
    """Each group's default option in an edition (as Settings.__post_init__ resolves it)."""
    fields = {f.name: f.default for f in dataclasses.fields(Settings)}
    chosen = {}
    for group, options in GROUPS.items():
        wanted = fields[group]
        if licences.permitted(options[wanted].uses, edition):
            chosen[group] = wanted
        else:
            chosen[group] = next(o for o in options if licences.permitted(options[o].uses, edition))
    return chosen


def render() -> str:
    from gpu_worker import manifests
    components_by_id=dict(licences.COMPONENTS)
    # Bundled declarative capabilities own their component terms. User-added
    # entries belong to that user's catalogue, never a generated repository file.
    bundled=manifests.manifests()
    for m in bundled.values():
        if m.component and m.id not in components_by_id:
            components_by_id[m.id]=licences.Component(m.id,m.component['what'],m.component['licence'],
                m.component['url'],m.component['tier'],'code')
    used_by: dict[str, list[str]] = {c: [] for c in components_by_id}
    for group, options in GROUPS.items():
        for option in options.values():
            for component in option.uses:
                used_by[component].append(f"{group}: `{option.id}`")
    from orchestrator import capabilities  # models fixed in the code (capability roles fixed:...), and their fallbacks

    for role in capabilities.load()["roles"]:
        for entry in (role, role.get("fallback") or {}):
            for component in entry.get("uses", []):
                used_by[component].append(f"fixed: `{role['id'][6:]}`{' (fallback)' if entry is not role else ''}")
    for m in bundled.values():
        for component in m.licence:
            if component in components_by_id and component not in licences.COMPONENTS:
                used_by[component].append(f"catalog: `{m.id}`")
    ops: dict[str, list[str]] = {c: [] for c in components_by_id}
    for op, components in OP_COMPONENTS.items():
        if op in ("segment", "embed", "cells"):  # listed per model below
            continue
        for component in components({}):
            ops[component].append(f"`{op}`")
    for op, models in (("segment", SEGMENT_MODELS), ("embed", EMBED_MODELS)):
        for model, components in models.items():
            for component in components:
                if f"`{op}` ({model})" not in ops[component]:
                    ops[component].append(f"`{op}` ({model})")
    for finder, (component, _cls) in CELL_FINDERS.items():
        ops[component].append(f"`cells` ({finder})")
    lines = [
        "# Licences",
        "",
        "Generated by `make licences` from `services/orchestrator/licences.py`, bundled catalog declarations and the options; do",
        "not edit by hand. The table records component declarations; software, weights, data and services",
        "retain their separate applicable terms. A tier is an application availability policy, not a licence",
        "grant or a finding that a component is legally suitable for a particular use.",
        "",
        "The **open** and **terms** tiers are available in both editions. The **non-commercial** tier is",
        "available only in the research edition (`MICROMIND_EDITION`, ADR 0005). Research is the default",
        "when the edition is unset or empty; explicit commercial and invalid nonempty overrides use the",
        "commercial gate (the user's 2026-10-08 amendment to ADR 0005).",
        "",
        "`services/noncommercial/` contains integration source for that policy tier; its folder name does",
        "not impose a blanket licence. Its [NOTICE](../services/noncommercial/NOTICE) distinguishes",
        "project-authored wrappers, fetched software, weights and training/input data. Training-data",
        "declarations alone do not determine the legal effect on weights or clear a particular use.",
        "",
        "| Component | Tier | Licence | Kind | Options that use it | GPU worker ops |",
        "|---|---|---|---|---|---|",
    ]
    for c in components_by_id.values():
        lines.append(f"| [{c.what}]({c.url}) | {TIER_WORDS[c.tier]} | {c.licence} | {c.kind} | "
                     f"{', '.join(used_by[c.id]) or '-'} | {', '.join(ops[c.id]) or '-'} |")
    lines += ["", "## Defaults by edition", "", "| Job | Commercial | Research |", "|---|---|---|"]
    commercial, research = _defaults("commercial"), _defaults("research")
    for group in GROUPS:
        lines.append(f"| {group} | `{commercial[group]}` | `{research[group]}` |")
    packages = _groups_by_package()
    noncommercial = sorted(p for p, g in packages.items() if g == "noncommercial")
    lines += ["", "## Python dependency groups", "",
              f"Packages in the `noncommercial` policy group (each keeps its own terms): {', '.join(f'`{p}`' for p in noncommercial) or 'none'}.", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("docs/licences.md is out of date: run make licences", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} (edition here: {licences.edition()})")
    for c in licences.COMPONENTS.values():
        if c.adapter:
            installed = importlib.util.find_spec(c.adapter.split(".")[0]) is not None
            print(f"  {c.id}: {'installed' if installed else 'not installed'} ({c.adapter})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
