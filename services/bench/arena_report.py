"""Scoreboard for the blind A/B/C votes (services/logs/votes.jsonl) -> docs/bench/arena.md.

For each kind of trial (outline, ask) and each option: how often it took part, won, tied,
or was in a trial where none were right, with its median time. The recommended default is
the option with the best win rate among those seen at least MIN_TRIALS times; a near tie
(within 10 points) goes to the faster option. Votes made by test harnesses are skipped.

  python -m bench.arena_report [--votes path] [--out path]
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from orchestrator.arena import MIN_TRIALS, arm_label, load_votes as load, recommend, score
from orchestrator.paths import Paths

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "bench" / "arena.md"
KIND_TITLES = {"outline": "Outlines (one click, several outline models)", "ask": "Answers (one question, several vision models)"}


def render(votes: list[dict]) -> str:
    lines = ["# Blind A/B/C results", ""]
    if not votes:
        return "\n".join(lines + ["No votes yet. Turn on Blind A/B/C test in the studio's model picker.", ""])
    lines += [
        f"{len(votes)} votes from the studio ({votes[0]['at'][:10]} to {votes[-1]['at'][:10]}). "
        "Options were shown as A/B/C in shuffled order; names were revealed after each vote. "
        "Generated by `python -m bench.arena_report`.",
        "",
    ]
    table = score(votes)  # one row per option and policy, never pooled (ADR 0011)
    for kind in ("outline", "ask"):
        rows = table.get(kind)
        if not rows:
            continue
        lines += [f"## {KIND_TITLES[kind]}", "", "| Option | Policy | Trials | Wins | Win rate | Ties | None right | Failed | Median time |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for key, r in sorted(rows.items(), key=lambda kv: -kv[1]["wins"] / kv[1]["trials"]):
            option, policy = key.rsplit("@", 1)
            median = f"{np.median(r['ms']) / 1000:.2f} s" if r["ms"] else "n/a"
            lines.append(f"| {arm_label(kind, option)} | {policy} | {r['trials']} | {r['wins']} | {r['wins'] / r['trials']:.0%} | "
                         f"{r['ties']} | {r['none']} | {r['failed']} | {median} |")
        # Defaults are chosen on "route" votes only: what users get.
        pick = recommend({k.rsplit("@", 1)[0]: r for k, r in rows.items() if k.endswith("@route")}, kind)
        lines += ["", f"Recommended default: **{arm_label(kind, pick)}**." if pick else
                  f"Not enough votes for a recommendation yet (each option needs {MIN_TRIALS}).", ""]
        notes = [v for v in votes if v["kind"] == kind and v.get("note")]
        if notes:
            lines += ["Notes:", ""]
            for v in notes:
                won = arm_label(kind, v["winnerOption"]) if v.get("winnerOption") else v["winner"]
                lines.append(f"- {won}: {v['note']}")
            lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--votes", default=str(Paths.from_env().votes_log))
    parser.add_argument("--out", default=str(OUT))
    args = parser.parse_args()
    text = render(load(Path(args.votes)))
    Path(args.out).write_text(text)
    print(text)


if __name__ == "__main__":
    main()
